"""The four-atlas ensemble (memo 0017): checks, CV evidence, and the ONE frozen measurement.

Three modes, from the repository root:

    python scripts/ensemble.py                 # check only: members, hashes, participants
    python scripts/ensemble.py --cv            # CV evidence from the out-of-fold files
    python scripts/ensemble.py --measure-once  # the single frozen-set measurement

The default only checks the inputs and computes no metric, so it can be run any time.
--cv reads the development out-of-fold files only, never the frozen set.
--measure-once averages the four final models' saved frozen-set predictions (memo 0017,
section 1), writes runs/frozen_predictions/ensemble_<id>_frozen.csv, appends one record to
runs/ensemble_log.jsonl and writes docs/reports/ensemble.md. It refuses to run if that log
already holds a measurement: the frozen set is measured once, and the result is reported
whatever it is. The record is kept out of the run log, whose database table (memo 0008)
holds training runs; `scripts/check_integrity.py` checks it (section 8).

No model is run and nothing is fitted. Needs no GPU, no connectomes and no PyTorch.
"""
import argparse
import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path

from neurographx import datasource
from neurographx.m3_model.ensemble import (
    MEMBERS,
    ORDER,
    THRESHOLD,
    append_ensemble_record,
    check_members,
    cv_evidence,
    frozen_ensemble,
    load_frozen_members,
    previous_measurements,
    wilson,
)
from neurographx.m3_model.run_logger import get_run, new_run_id, read_registry

LABELS = {"aal": "AAL", "cc200": "CC200", "ho": "Harvard-Oxford",
          "dosenbach160": "Dosenbach 160", "ensemble": "**Ensemble (memo 0017)**"}
REPORT = Path("docs/reports/ensemble.md")


def _f(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def cv_table(cv: dict, atlases) -> list[str]:
    lines = ["| Model | Accuracy | Balanced accuracy | AUC |", "|---|---|---|---|"]
    for key in [*atlases, "ensemble"]:
        m = cv[key]
        cells = [f"{_f(m[k]['mean'])} ({_f(m[k]['sd'])})"
                 for k in ("accuracy", "balanced_accuracy", "auc")]
        lines.append(f"| {LABELS.get(key, key)} | " + " | ".join(cells) + " |")
    return lines


def frozen_table(members: dict, root: Path, ensemble: dict) -> list[str]:
    log = datasource.run_log(root)
    lines = ["| Model | Run | Accuracy (95% CI) | Balanced accuracy | AUC | Baseline |",
             "|---|---|---|---|---|---|"]
    for atlas, run_id in members.items():
        fr = get_run(run_id, log)["metrics"]["frozen"]
        tn, _, _, tp = fr["confusion_tn_fp_fn_tp"]
        lo, hi = wilson(tn + tp, fr["n"])
        lines.append(f"| {LABELS.get(atlas, atlas)} | `{run_id}` | {_f(fr['accuracy'], 2)} "
                     f"({lo:.2f}–{hi:.2f}) | {_f(fr['balanced_accuracy'])} | {_f(fr['auc'])} | "
                     f"{_f(fr['majority_baseline'], 2)} |")
    lo, hi = ensemble["accuracy_ci95_wilson"]
    lines.append(f"| {LABELS['ensemble']} | mean of the four | {_f(ensemble['accuracy'], 2)} "
                 f"({lo:.2f}–{hi:.2f}) | {_f(ensemble['balanced_accuracy'])} | "
                 f"{_f(ensemble['auc'])} | {_f(ensemble['majority_baseline'], 2)} |")
    return lines


def report(run_id: str, members: dict, root: Path, cv: dict, ens: dict, pred_file: str) -> str:
    tn, fp, fn, tp = ens["confusion_tn_fp_fn_tp"]
    return "\n".join([
        "# The four-atlas ensemble (memo 0017)",
        "",
        f"Generated by `scripts/ensemble.py --measure-once`, ensemble `{run_id}`. The rule (equal-"
        f"weight mean of the four final models' probability of autism, autism when the mean "
        f"is at least {THRESHOLD}) was fixed in memo 0017 before this measurement. The frozen "
        "set was measured once; the result is reported as it came out.",
        "",
        f"## Cross-validation ({cv['n']} development participants, out-of-fold)",
        "",
        "Mean (standard deviation) over the five folds. Optimistic: each member is the best "
        "of twelve configurations (memo 0011).",
        "",
        *cv_table(cv, list(members)),
        "",
        "## Frozen evaluation set (100 participants, measured once)",
        "",
        *frozen_table(members, root, ens),
        "",
        f"Ensemble confusion matrix (true control predicted control, control predicted autism, "
        f"autism predicted control, true autism predicted autism): {tn}, {fp}, {fn}, {tp}. "
        f"Predicted autism for {ens['predicted_autism']} of {ens['n']}.",
        "",
        f"Per-participant predictions: `{pred_file}`.",
        "",
    ])


def main(argv=None, root: Path | None = None, members: dict | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--cv", action="store_true", help="CV evidence from out-of-fold files")
    mode.add_argument("--measure-once", dest="measure_once", action="store_true",
                      help="the single frozen-set measurement (memo 0017, section 4)")
    args = p.parse_args(argv)

    root = Path(root or datasource.data_root())
    members = dict(members or MEMBERS)
    log = datasource.run_log(root)
    atlases = tuple(a for a in ORDER if a in members) + tuple(a for a in members
                                                             if a not in ORDER)
    members = {a: members[a] for a in atlases}

    check_members(read_registry(datasource.model_registry(root)), members)
    dataset = get_run(members[atlases[0]], log)["dataset"]

    if args.cv:
        cv = cv_evidence(root, members, log)
        print("\n".join(cv_table(cv, atlases)))
        return 0

    table = load_frozen_members(root, members, log)  # hashes, participants, labels
    ens_log = datasource.ensemble_log(root)
    earlier = previous_measurements(ens_log, dataset)
    if not args.measure_once:
        print(f"Check passed: {len(atlases)} members {members}, hashes match, "
              f"{len(table)} participants with identical labels. No metric was computed.")
        if earlier:
            print(f"Already measured: {earlier[-1]['ensemble_id']}.")
        return 0

    if earlier:
        raise SystemExit(f"The ensemble was already measured on the frozen set "
                         f"({earlier[-1]['ensemble_id']}). Memo 0017: it is measured once.")

    cv = cv_evidence(root, members, log)
    metrics, rows = frozen_ensemble(table, atlases)
    run_id = new_run_id()
    pred_rel = Path("runs/frozen_predictions") / f"ensemble_{run_id}_frozen.csv"
    pred_path = root / pred_rel
    pred_path.parent.mkdir(parents=True, exist_ok=True)
    cols = ["SUB_ID", "FILE_ID", "SITE_ID", "label", "prob_autism", "prediction",
            *[f"prob_{a}" for a in atlases]]
    rows.loc[:, cols].to_csv(pred_path, index=False, float_format="%.6f", lineterminator="\n")
    sha = hashlib.sha256(pred_path.read_bytes()).hexdigest()
    metrics["predictions"] = {"file": pred_rel.as_posix(), "n": len(rows), "sha256": sha}

    append_ensemble_record(ens_log, {
        "ensemble_id": run_id,
        "timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "dataset": dataset, "members": members,
        "rule": {"combine": "mean probability of autism", "weights": "equal",
                 "threshold": THRESHOLD, "probabilities": "raw", "memo": "0017"},
        "metrics": {"frozen": {k: v for k, v in metrics.items() if k != "predictions"},
                    "cv": cv["ensemble"]},
        "predictions": metrics.pop("predictions"),
    })

    out = root / REPORT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report(run_id, members, root, cv, metrics, pred_rel.as_posix()),
                   encoding="utf-8", newline="\n")
    print(f"Frozen set, ensemble: {metrics}")
    print(f"Ensemble {run_id} recorded in {datasource.ENSEMBLE_LOG.as_posix()}; "
          f"predictions {pred_rel}; report {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
