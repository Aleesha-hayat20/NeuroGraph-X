"""Write a model card per registered atlas and one results table (#99), from the logs only.

Every number comes from the run log, the registry and the calibration files, so a card can
never disagree with the evidence. Re-run it after any change to those files.

Writes:
    docs/model_cards/<atlas>.md        one card per registered model
    docs/reports/final_results.md      the four models side by side (report and slides)

Usage (from the repository root):
    python scripts/make_model_cards.py
    NGX_DATA=fixtures python scripts/make_model_cards.py --out /tmp/cards   # fixture check
"""
import argparse
import json
import math
from pathlib import Path

from neurographx import datasource
from neurographx.m3_model.run_logger import get_run, read_registry

LABELS = {"aal": "AAL (116 regions)", "cc200": "CC200 (200 regions)",
          "ho": "Harvard-Oxford (111 regions)", "dosenbach160": "Dosenbach 160 (161 regions)"}
ORDER = ("aal", "cc200", "ho", "dosenbach160")


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% Wilson interval for a proportion k/n (better than the normal one for n = 100)."""
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (centre - half, centre + half)


def _fmt(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def gather(root: Path | None) -> list[dict]:
    registry = read_registry(datasource.model_registry(root))
    log = datasource.run_log(root)
    rows = []
    for atlas in [a for a in ORDER if a in registry] + [a for a in registry if a not in ORDER]:
        final = get_run(registry[atlas]["run_id"], log)
        cv = get_run(final["metrics"].get("cv_run_id"), log) if final else None
        cal_path = Path(datasource.model_registry(root)).parent / "calibration" / \
            f"{atlas}_{final['run_id']}.json"
        cal = json.loads(cal_path.read_text(encoding="utf-8")) if cal_path.exists() else None
        rows.append({"atlas": atlas, "final": final, "cv": cv, "cal": cal})
    return rows


def card(row: dict) -> str:
    atlas, f, cv, cal = row["atlas"], row["final"], row["cv"], row["cal"]
    hp, dc, fr = f["hyperparameters"], f["data_config"], f["metrics"]["frozen"]
    tn, fp, fn, tp = fr["confusion_tn_fp_fn_tp"]
    correct = tn + tp
    lo, hi = wilson(correct, fr["n"])
    cvm = cv["metrics"] if cv else {}

    def cvstat(key):
        v = cvm.get(key)
        return f"{v['mean']:.4f} (SD {v['sd']:.4f})" if isinstance(v, dict) else "n/a"

    lines = [
        f"# Model card: NeuroGraph-X, {LABELS.get(atlas, atlas)}",
        "",
        "Generated by `scripts/make_model_cards.py` from the run log, the model registry and "
        "the calibration file. Do not edit the numbers by hand; re-run the script.",
        "",
        "## Model",
        f"- **Final run:** `{f['run_id']}` ({f['timestamp'][:10]}), code `{f.get('git_commit')}`; "
        f"settings from CV run `{cv['run_id'] if cv else 'n/a'}` (memo 0011 selection).",
        f"- **Architecture:** graph convolutional network, {hp.get('layers')} GCN layers of "
        f"{hp.get('hidden')} units, mean-pool readout, MLP head, dropout {hp.get('dropout')}.",
        f"- **Graph:** one graph per participant; nodes are the atlas regions, node features "
        f"the Fisher-z correlation row, edges the strongest {dc['density']:.0%} of |z| "
        f"(missing values filled with {dc['fill_nan']}).",
        f"- **Training:** Adam, learning rate {hp.get('lr')}, batch {hp.get('batch_size')}, "
        f"{hp.get('epochs')} epochs (median best epoch of the CV folds), class-weighted loss "
        f"{'on' if hp.get('class_weighted') else 'off'}, seed {f['seed']}, on all "
        f"{f['split_sizes']['train']} development participants.",
        f"- **Checkpoint:** `{f['checkpoint_path']}`, SHA-256 `{f.get('checkpoint_sha256')}`; "
        f"reloading it reproduces identical predictions: {f.get('reload_identical')}.",
        "",
        "## Intended use",
        "Research and teaching on group differences in resting-state connectivity. **Not a "
        "diagnostic or medical device:** a prediction is a model output about one scan, with "
        "the accuracy below, and must not inform any decision about a person.",
        "",
        "## Data",
        "ABIDE I, Preprocessed Connectomes Project, CPAC pipeline with band-pass filtering and "
        "global signal regression (memo 0002); quality control exclusions as listed in "
        "`docs/reports/exclusion_log.csv`. The frozen "
        f"evaluation set ({fr['n']} participants, stratified by site and group, memo 0005) was "
        "never used "
        "for training, tuning or calibration.",
        "",
        "## Results",
        "| | Cross-validation (development) | Frozen evaluation set |",
        "|---|---|---|",
        f"| Accuracy | {cvstat('cv_accuracy')} | {fr['accuracy']:.3f} "
        f"(95% CI {lo:.3f} to {hi:.3f}) |",
        f"| Balanced accuracy | {cvstat('cv_balanced_accuracy')} | "
        f"{fr['balanced_accuracy']:.3f} |",
        f"| AUC | {cvstat('cv_auc')} | {_fmt(fr.get('auc'))} |",
        f"| Majority-class baseline | {cvstat('cv_majority_baseline')} | "
        f"{fr['majority_baseline']:.2f} |",
        "",
        f"Frozen-set confusion matrix: {tn} true controls, {fp} controls predicted autism, "
        f"{fn} autism predicted control, {tp} true autism ({fr['n']} participants).",
        "",
        "The cross-validation score is optimistic: this configuration won a comparison of "
        "twelve on the same folds (memo 0011). The frozen-set number is the estimate to quote.",
    ]
    if f.get("repeat_frozen_measurement"):
        lines += ["", f"**Declared repeat measurement.** This atlas was measured on the frozen "
                  f"set before; reason logged: \"{f.get('repeat_reason')}\". The earlier "
                  "result stays in the run log."]
    lines += ["", "## Confidence calibration (memo 0010)"]
    if cal:
        o, fz = cal["oof"], cal.get("frozen")
        lines += [
            f"Platt scaling fitted on the CV run's out-of-fold predictions ({cal['n']} "
            f"participants): a = {cal['a']}, b = {cal['b']}.",
            "",
            "| | ECE before | ECE after | Brier before | Brier after |",
            "|---|---|---|---|---|",
            f"| Out-of-fold (cross-fitted) | {o['before']['ece']} | "
            f"{o['after_cross_fitted']['ece']} | {o['before']['brier']} | "
            f"{o['after_cross_fitted']['brier']} |",
        ]
        if fz:
            lines.append(f"| Frozen set | {fz['before']['ece']} | {fz['after']['ece']} | "
                         f"{fz['before']['brier']} | {fz['after']['brier']} |")
            lines += ["", f"Calibration keeps the ranking (AUC unchanged); "
                      f"{fz['prediction_flips']} frozen prediction(s) cross the 0.5 threshold, "
                      f"accuracy {fz['accuracy_before']} before and {fz['accuracy_after']} after."]
        lines += ["", f"Reliability diagram: `docs/reports/figures/calibration_{atlas}_"
                  f"{f['run_id']}.png`."]
    else:
        lines.append("Not calibrated yet: confidences are raw softmax probabilities.")
    lines += [
        "", "## Limitations",
        "- Modest accuracy: useful for studying group differences, far from individual use.",
        f"- One frozen set of {fr['n']} gives a wide interval (above); differences of a few "
        "points between atlases are within it.",
        "- ABIDE I only: sites, scanners and protocols differ, and no external dataset was "
        "tested.",
        "- Trained on all development participants, so a prediction for one of them is not an "
        "independent test; demonstrations use frozen-set participants.",
        "",
        "## Licence",
        "ABIDE I data: CC BY-NC-SA 3.0 (non-commercial research use).",
    ]
    return "\n".join(lines) + "\n"


def results_table(rows: list[dict]) -> str:
    out = ["# Final models: results", "",
           "Generated by `scripts/make_model_cards.py`. Frozen set measured once per final run; "
           "CV numbers are the selected configuration's (optimistic, see memo 0011).", "",
           "| Atlas | Final run | CV balanced acc. | Frozen acc. (95% CI) | Frozen balanced | "
           "Frozen AUC | Baseline | ECE frozen before → after |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        f, fr = r["final"], r["final"]["metrics"]["frozen"]
        tn, fp, fn, tp = fr["confusion_tn_fp_fn_tp"]
        lo, hi = wilson(tn + tp, fr["n"])
        cvb = (r["cv"] or {}).get("metrics", {}).get("cv_balanced_accuracy")
        fz = (r["cal"] or {}).get("frozen")
        ece = f"{fz['before']['ece']} → {fz['after']['ece']}" if fz else "not calibrated"
        out.append(f"| {LABELS.get(r['atlas'], r['atlas'])} | `{f['run_id']}` | "
                   f"{_fmt(cvb['mean'] if cvb else None, 4)} | {fr['accuracy']:.2f} "
                   f"({lo:.2f}–{hi:.2f}) | {fr['balanced_accuracy']:.3f} | "
                   f"{_fmt(fr.get('auc'))} | {fr['majority_baseline']:.2f} | {ece} |")
    return "\n".join(out) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", type=Path, default=None,
                   help="folder for the files (default: docs/ of the repository)")
    args = p.parse_args()
    rows = gather(None)
    cards = (args.out / "model_cards") if args.out else Path("docs/model_cards")
    reports = (args.out / "reports") if args.out else Path("docs/reports")
    cards.mkdir(parents=True, exist_ok=True)
    reports.mkdir(parents=True, exist_ok=True)
    for row in rows:
        (cards / f"{row['atlas']}.md").write_text(card(row), encoding="utf-8", newline="\n")
        print(f"wrote {cards / (row['atlas'] + '.md')}")
    (reports / "final_results.md").write_text(results_table(rows), encoding="utf-8",
                                              newline="\n")
    print(f"wrote {reports / 'final_results.md'}")


if __name__ == "__main__":
    main()
